// Rebuilds extension/lib/public-suffixes.js from a downloaded copy of the Public Suffix List.
// node tests/update-public-suffixes.mjs <public_suffix_list.dat>
// Only the ICANN section is kept: FREE_HOSTING in analyzer.js covers hosting platforms.
// One-label rules are dropped because the last label is a suffix by default.
import { readFileSync, writeFileSync } from 'node:fs';

const dat = readFileSync(process.argv[2], 'utf8');
const icann = dat.split('// ===END ICANN DOMAINS===')[0];
const version = (dat.match(/^\/\/ VERSION: (.+)$/m) || [])[1] || 'unknown';
const rules = icann.split(/\r?\n/).map((s) => s.trim()).filter((s) => s && !s.startsWith('//') && s.includes('.'));

const out = `// Public Suffix List, ICANN section, multi-label rules only. Version: ${version}
// This Source Code Form is subject to the terms of the Mozilla Public
// License, v. 2.0. If a copy of the MPL was not distributed with this
// file, You can obtain one at https://mozilla.org/MPL/2.0/.
// Source: https://publicsuffix.org/list/public_suffix_list.dat
// Generated by tests/update-public-suffixes.mjs. Do not edit by hand.
(function (root) {
  root.VSPublicSuffixes = '${rules.join(' ')}';
  if (typeof module !== 'undefined' && module.exports) module.exports = root.VSPublicSuffixes;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
writeFileSync(new URL('../extension/lib/public-suffixes.js', import.meta.url), out);
console.log('rules', rules.length, 'bytes', Buffer.byteLength(out), 'version', version);
